// Theorem-shaped tests for the dramaturgy layer, built on the REAL ludics operators (incarnation,
// orthogonality, bi-orthogonal closure) over genuinely-interacting designs. Run against dist.
import { test } from "node:test";
import assert from "node:assert/strict";

import { designFromActs, orthogonal, stage, paradoxOfTheActor, spectator, dissensus } from "../dist/index.mjs";

// designs over real loci (keys are dotted addresses; "" = root). proponent↦potential, opponent↦active.
const D = (entries) => designFromActs(new Map(entries));
const A = D([["", "proponent"], ["0", "proponent"], ["1", "proponent"]]);   // commits at root, 0, and ballast 1
const A2 = D([["", "proponent"], ["0", "proponent"], ["2", "proponent"]]);  // same front, different ballast (2)
const C1 = D([["", "opponent"], ["0", "opponent"]]);                        // an audience that meets root + 0, not 1/2
const C2 = D([["", "opponent"], ["0", "opponent"], ["5", "proponent"]]);    // an audience that ALSO bears a proponent move

const U = [A, C1];          // ambient universe for the closure
const troupe = [A];         // the behaviour is generated by the actor A

test("sanity: A and the counter C1 are orthogonal (their cut converges to the Daimon)", () => {
  assert.equal(orthogonal(A, C1), true);
  // C1 does not meet the ballast locus "1" — it only commits at root and 0.
});

test("FRONT/BACK STAGE = incarnation/ballast: the audience meets the front; the back stage is private", () => {
  const s = stage(A, troupe, U);
  // front stage = the loci the audience (B^⊥ = {C1}) actually visits: root and 0.
  assert.deepEqual(s.frontStage.entries.map((e) => e.locusKey).sort(), ["", "0"]);
  // back stage = the ballast locus 1: committed by the actor, met by no counter.
  assert.deepEqual(s.backStage.entries.map((e) => e.locusKey), ["1"]);
  assert.equal(s.frontLoci, 2);
  assert.equal(s.backLoci, 1);
  assert.equal(s.material, false, "the actor holds a reserve — it is not material");
});

test("THE PARADOX OF THE ACTOR (theorem): same front stage ⇒ audience-indistinguishable despite differing backstage", () => {
  // A and A2 share a front stage (root, 0) but differ backstage (ballast 1 vs 2).
  const p = paradoxOfTheActor(A, A2, troupe, U);
  assert.equal(p.sameFrontStage, true);
  assert.equal(p.backstageDiffers, true);
  assert.equal(p.indistinguishable, true, "the audience cannot tell them apart — affect is in the cut, not the interior");
  assert.equal(p.paradox, true);
});

test("SPECTACLE (Debord): an audience that can only respond, never play", () => {
  // B^⊥ = {C1}; C1 bears no proponent move → it can never step into play.
  const s = spectator(troupe, U);
  assert.equal(s.audience, 1);
  assert.equal(s.emancipated, false);
  assert.equal(s.spectacle, true);
});

test("EMANCIPATED SPECTATOR (Rancière): a counter that bears a proponent move can step into play", () => {
  // swap the audience for C2, which also makes a proponent move at locus 5.
  const s = spectator([A], [A, C2]);
  assert.equal(s.emancipatedCount >= 1, true);
  assert.equal(s.emancipated, true);
  assert.equal(s.spectacle, false);
});

test("DISSENSUS (Rancière): a newcomer that shifts the bi-orthogonal closure redistributes what counts", () => {
  // admitting C1 to the troupe grows the closure {A} → {A, C1}: it redistributes.
  const d = dissensus(troupe, C1, U);
  assert.equal(d.redistributes, true);
  assert.equal(d.consensus, false);
  // admitting A again changes nothing — already counted: consensus.
  const same = dissensus(troupe, A, U);
  assert.equal(same.redistributes, false);
  assert.equal(same.consensus, true);
});
